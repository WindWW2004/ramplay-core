#!/usr/bin/env python3
"""Font and palette sources -> C headers and the core's TS table.

    python3 tools/gen_tables.py            write the three files
    python3 tools/gen_tables.py --check    exit 1 if a file is out of date

Sources:  firmware/common/font.txt, firmware/common/palette.txt
Outputs:  firmware/common/rpl_font.h, firmware/common/default_palette.h,
          src/video/tables.ts
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMON = ROOT / "firmware" / "common"
FIRST, LAST = 0x20, 0x7E


def read_font(path: Path) -> list[list[int]]:
    """95 glyphs, 8 row bytes each. Bit 7 is the left pixel of the cell."""
    glyphs: dict[int, list[int]] = {}
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("//"):
            continue
        parts = line.split()
        code = int(parts[0], 16)
        rows = parts[1:]
        if len(rows) not in (7, 8) or any(len(r) != 5 or set(r) - set(".#") for r in rows):
            raise SystemExit(f"{path.name}:{n}: a glyph is 7 or 8 rows of 5 '.' or '#'")
        if code in glyphs:
            raise SystemExit(f"{path.name}:{n}: glyph {code:02X} is defined twice")
        data = [sum(1 << (6 - k) for k, ch in enumerate(r) if ch == "#") for r in rows]
        glyphs[code] = data + [0] * (8 - len(data))
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing or len(glyphs) != LAST - FIRST + 1:
        raise SystemExit(f"{path.name}: need exactly ${FIRST:02X} to ${LAST:02X}; missing {missing}")
    return [glyphs[c] for c in range(FIRST, LAST + 1)]


def read_palette(path: Path) -> list[int]:
    """16 colors as RGB565."""
    out: list[int] = []
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("//"):
            continue
        rgb = int(line.split()[0], 16)
        r, g, b = rgb >> 16, (rgb >> 8) & 0xFF, rgb & 0xFF
        out.append((r >> 3) << 11 | (g >> 2) << 5 | (b >> 3))
    if len(out) != 16:
        raise SystemExit(f"{path.name}: need 16 colors, found {len(out)}")
    return out


def outputs() -> dict[Path, str]:
    font = read_font(COMMON / "font.txt")
    pal = read_palette(COMMON / "palette.txt")
    note = "Generated by tools/gen_tables.py. Do not edit."

    font_h = (
        f"/* {note} Source: font.txt */\n"
        "#ifndef RPL_FONT_H\n#define RPL_FONT_H\n\n#include <stdint.h>\n\n"
        f"#define RPL_FONT_FIRST 0x{FIRST:02X}\n#define RPL_FONT_LAST 0x{LAST:02X}\n\n"
        "/* One byte per row, bit 7 = left pixel. */\n"
        f"static const uint8_t rpl_font[{len(font)}][8] = {{\n"
        + ",\n".join("    {" + ", ".join(f"0x{b:02X}" for b in g) + "}" for g in font)
        + "\n};\n\n#endif\n"
    )
    pal_h = (
        f"/* {note} Source: palette.txt */\n"
        "#ifndef RPL_DEFAULT_PALETTE_H\n#define RPL_DEFAULT_PALETTE_H\n\n#include <stdint.h>\n\n"
        "/* RGB565. Index 0 is transparent in sprites. */\n"
        "static const uint16_t rpl_default_palette[16] = {\n    "
        + ", ".join(f"0x{c:04X}" for c in pal[:8]) + ",\n    "
        + ", ".join(f"0x{c:04X}" for c in pal[8:]) + "\n};\n\n#endif\n"
    )
    ts = (
        f"// {note} Sources: firmware/common/font.txt, palette.txt\n"
        f"export const FONT_FIRST = 0x{FIRST:02X};\nexport const FONT_LAST = 0x{LAST:02X};\n\n"
        "/** 95 glyphs, 8 bytes each, bit 7 = left pixel. */\n"
        "export const FONT = new Uint8Array([\n"
        + "\n".join("  " + ", ".join(f"0x{b:02X}" for b in g) + "," for g in font)
        + "\n]);\n\n/** RGB565. */\nexport const DEFAULT_PALETTE = new Uint16Array([\n  "
        + ", ".join(f"0x{c:04X}" for c in pal) + ",\n]);\n"
    )
    return {
        COMMON / "rpl_font.h": font_h,
        COMMON / "default_palette.h": pal_h,
        ROOT / "src" / "video" / "tables.ts": ts,
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = False
    for path, text in outputs().items():
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"out of date: {path.relative_to(ROOT)} (run tools/gen_tables.py)")
                stale = True
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
